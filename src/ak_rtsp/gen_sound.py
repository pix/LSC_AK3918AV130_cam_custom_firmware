#!/usr/bin/env python3
"""Bake sounds/custom.wav (any format ffmpeg reads) into sounds_custom.c as
8 kHz mono s16 PCM. Without the WAV (or ffmpeg) an empty sound is generated.
The generated file and sounds/ are git-ignored (personal sounds stay local)."""
import os, shutil, subprocess, sys
src, dst = sys.argv[1], sys.argv[2]
pcm = b""
if os.path.exists(src) and shutil.which("ffmpeg"):
    pcm = subprocess.run(["ffmpeg", "-v", "error", "-i", src, "-t", "20", "-ac", "1", "-ar", "8000",
                          "-f", "s16le", "-"], check=True, capture_output=True).stdout
n = len(pcm) // 2
with open(dst, "w") as f:
    f.write("/* Generated by gen_sound.py from %s - do not edit or commit. */\n" % src)
    f.write("#include <stddef.h>\n#include <stdint.h>\n")
    f.write("const size_t speaker_custom_len = %d;\nconst int16_t speaker_custom_pcm[%d] = {\n" % (n, max(n, 1)))
    vals = [int.from_bytes(pcm[i:i + 2], "little", signed=True) for i in range(0, n * 2, 2)] or [0]
    for i in range(0, len(vals), 16):
        f.write("  " + ",".join(str(v) for v in vals[i:i + 16]) + ",\n")
    f.write("};\n")
print("custom sound: %d samples (%.2f s)" % (n, n / 8000))
